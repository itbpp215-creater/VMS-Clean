"""Expose authenticated preparation, status, cancellation, health, and media.

This module composes the reviewed resolver, scheduler, store, health gate, and
NVENC transcoder behind FastAPI.  Browser routes trust only gateway assertions,
return stable public fields/codes, and serve derived indexed MP4 bytes without
accepting source URLs or filesystem paths.  It owns no Docker, camera, Frigate
configuration, recording-file, or service-control capability.
"""

