# The external media URL contains only an opaque digest-like key.  Eight
# characters remain accepted for deterministic API fakes; production keys are
# complete lowercase SHA-256 digests generated by MediaStore's reviewed caller.
_PUBLIC_CACHE_KEY = re.compile(r"[0-9a-f]{8,64}")
_MEDIA_PREFIX = "/api/media-compat/media"
_POLL_RETRY_AFTER_MS = 500
_HEALTH_RETRY_AFTER_MS = 1000
_HEALTH_SNAPSHOT_FRESH_SECONDS = 1.0
_ResultT = TypeVar("_ResultT")
# The pinned Frigate runtime image exposes this NVIDIA-capable FFmpeg toolchain;
# Task 7 packages the same image rather than looking up executables from PATH.
_FFMPEG_PATH = "/usr/lib/ffmpeg/7.0/bin/ffmpeg"
_FFPROBE_PATH = "/usr/lib/ffmpeg/7.0/bin/ffprobe"
_NVIDIA_SMI_PATH = "/usr/bin/nvidia-smi"
_CACHE_ROOT = Path("/cache")
_WORK_ROOT = Path("/work")


class ProbedJobFactory:
    """Create scheduler jobs from real bounded source-media facts off-loop.

    Construction retains one reviewed Transcoder.  Calling the factory accepts
    only a resolver-created source and exact MediaStore reservation, then runs
    the fixed ffprobe boundary in a worker thread.  It returns a fact-complete
    :class:`TranscodeJob` and stores or exposes no probe JSON, credentials, or
    source diagnostics.
    """

    def __init__(self, transcoder: Transcoder) -> None:
        """Retain a Transcoder dependency without starting a process or I/O."""
        if not isinstance(transcoder, Transcoder):
            raise TypeError("transcoder must be a Transcoder")
        self._transcoder = transcoder

    async def __call__(
        self,
        source: ResolvedSource,
        reservation: Reservation,
    ) -> TranscodeJob:
        """Probe one fixed source and bind facts to the exact reservation.

        Inputs are the reviewed immutable source and active reservation; output
        is a complete transcode contract.  The only side effect is a bounded
        ffprobe child executed through ``asyncio.to_thread`` so Scheduler's event
        loop remains responsive during source inspection.
        """
        if not isinstance(source, ResolvedSource) or not isinstance(reservation, Reservation):
            raise TypeError("source and reservation contracts are required")
        return await asyncio.to_thread(
            self._transcoder.probe_source,
            source.upstream_url,
            reservation.partial_path,
            reservation.owned_partial,
        )


def _public_media_url(cache_key: str) -> str:
    """Return a safe same-origin URL for one opaque validated cache key.

    ``cache_key`` is Scheduler-generated internal state; output contains no host,
    source, or path authority.  Invalid bypassed job data raises ``ValueError``
    before it can become a response header or URL.
    """
    if not isinstance(cache_key, str) or _PUBLIC_CACHE_KEY.fullmatch(cache_key) is None:
        raise ValueError("invalid public cache key")
    return f"{_MEDIA_PREFIX}/{cache_key}.mp4"


def _public_job_error(job: Job) -> PublicErrorCode | None:
    """Map private scheduler reasons to the stable public error vocabulary.

    Input is an in-memory Job and output is a safe code or ``None``.  The pure
    function never returns health reason detail, process diagnostics, source
    facts, or arbitrary strings retained by a bypassed component.
    """
    if job.state == "cancelled":
        return "cancelled"
    if job.state == "failed":
        return job.last_error_code if job.last_error_code in {"invalid_source", "transcode_failed"} else "transcode_failed"
    if job.state == "queued" and job.last_error_code in {
        "frigate_unavailable",
        "encoder_unavailable",
        "gpu_temperature",
        "gpu_memory",
        "storage_unavailable",
        "health_gate",
    }:
        return "health_gate"
    return None


def _prepare_response(job: Job) -> PrepareResponse:
    """Serialize only the four documented preparation fields from a Job.

    Input is a Scheduler-owned job and output is a strict Pydantic contract with
    no side effects.  Ready media receives a same-origin opaque URL; queued and
    running work receives bounded polling advice; terminal states expose neither
    a URL nor private errors through this initial response.
    """
    media_url = _public_media_url(job.cache_key) if job.state == "ready" else None
    retry_after_ms = _POLL_RETRY_AFTER_MS if job.state in {"queued", "running"} else None
    return PrepareResponse(
        state=job.state,  # type: ignore[arg-type]
        job_id=job.job_id,
        media_url=media_url,
        retry_after_ms=retry_after_ms,
    )


def _status_response(job: Job) -> JobStatusResponse:
    """Serialize public lifecycle fields without exposing private Job members.

    Input is an owner-authorized Scheduler job; output contains only state, an
    opaque identifier, optional ready URL, bounded retry advice, and a stable
    public error.  The pure conversion omits cache roots, source/upstream values,
    waiter identities, timings, and diagnostic strings.
    """
    media_url = _public_media_url(job.cache_key) if job.state == "ready" else None
    retry_after_ms = _POLL_RETRY_AFTER_MS if job.state in {"queued", "running"} else None
    return JobStatusResponse(
        state=job.state,  # type: ignore[arg-type]
        job_id=job.job_id,
        media_url=media_url,
        retry_after_ms=retry_after_ms,
        error_code=_public_job_error(job),
    )


def _error_response(
    status_code: int,
    code: PublicErrorCode,
    *,
    retry_after_ms: int | None = None,
    headers: dict[str, str] | None = None,
) -> JSONResponse:
    """Build one non-reflective JSON error with optional bounded retry advice.

    Inputs are trusted status/code values and safe server-generated metadata;
    output is a JSON response with no I/O.  No exception detail, request value,
    path, URL, credential, or process diagnostic can enter the body.
    """
    detail: dict[str, object] = {"code": code}
    if retry_after_ms is not None:
        detail["retry_after_ms"] = retry_after_ms
    return JSONResponse(status_code=status_code, content={"detail": detail}, headers=headers)


def _next_media_chunk(iterator: Iterator[bytes]) -> bytes | None:
    """Advance one synchronous bounded media iterator without leaking StopIteration.

    Input is the Task-3 stream iterator; output is its next non-empty byte chunk
    or ``None`` at completion.  The read side effect occurs only in the caller's
    worker thread, avoiding Python's prohibition on propagating StopIteration
    through an asyncio Future.
    """
    try:
        return next(iterator)
    except StopIteration:
        return None


class _HealthReadinessCache:
    """Single-flight coarse health snapshots behind a short freshness window."""

    def __init__(self, health: HealthGate, freshness_seconds: float) -> None:
        """Retain one reviewed gate and finite freshness without starting I/O."""
        if freshness_seconds <= 0:
            raise ValueError("health freshness must be positive")
        self._health = health
        self._freshness_seconds = freshness_seconds
        self._lock = asyncio.Lock()
        self._ready: bool | None = None
        self._expires_at = 0.0
        self._refresh_task: asyncio.Task[bool] | None = None

    async def readiness(self) -> bool:
        """Return cached coarse readiness or collect exactly one shared snapshot.

        The result contains no diagnostics.  Snapshot work runs in a worker and
        concurrent callers share the lock-protected refresh; both healthy and
        failed observations remain fresh only for the configured short window.
        """
        loop = asyncio.get_running_loop()
        async with self._lock:
            now = loop.time()
            if self._ready is not None and now < self._expires_at:
                return self._ready
            refresh = self._refresh_task
            if refresh is None:
                # The refresh Task, rather than its first request, owns the
                # worker probe.  Shielded joiners cannot cancel shared work.
                refresh = asyncio.create_task(
                    self._refresh(), name="media-compat-health-refresh"
                )
                self._refresh_task = refresh
        return await asyncio.shield(refresh)

    async def _refresh(self) -> bool:
        """Collect one coarse probe and publish it only for this refresh identity.

        The task catches ordinary HealthGate/runtime faults as not-ready, updates
        the short freshness window after probing, and clears the shared in-flight
        slot only when it still points to this exact task.  Request cancellation
        cannot cancel this task because all request waiters shield it.
        """
        current = asyncio.current_task()
        ready = False
        try:
            try:
                snapshot = await asyncio.to_thread(self._health.snapshot)
                decision = self._health.can_start(snapshot)
                ready = (
                    isinstance(snapshot, HealthSnapshot)
                    and isinstance(decision, GateDecision)
                    and decision.allowed
                )
            except Exception:
                ready = False
            async with self._lock:
                self._ready = ready
                self._expires_at = (
                    asyncio.get_running_loop().time() + self._freshness_seconds
                )
            return ready
        finally:
            async with self._lock:
                if self._refresh_task is current:
                    self._refresh_task = None


async def _await_executor_future_preserving_cancellation(
    pending: asyncio.Future[_ResultT],
) -> _ResultT:
    """Drain one shielded executor future through every caller cancellation.

    ``pending`` is already-running bounded worker work.  The return is its normal
    result and ordinary worker failures propagate unchanged when no cancellation
    occurred.  Every caller ``CancelledError`` is recorded while repeatedly
    shielding the same future until it settles; then the first authoritative
    cancellation is re-raised so the worker is never cancelled or abandoned.
    """
    cancellations: list[asyncio.CancelledError] = []
    while True:
        try:
            result = await asyncio.shield(pending)
        except asyncio.CancelledError as error:
            cancellations.append(error)
            if pending.done():
                # Consume any worker result/failure before preserving the
                # request's original cancellation and avoiding warning leaks.
                try:
                    pending.result()
                except BaseException:
                    pass
                raise cancellations[0]
            continue
        except Exception:
            if cancellations:
                raise cancellations[0]
            raise
        if cancellations:
            raise cancellations[0]
        return result


def _close_media_sync(iterator: Iterator[bytes] | None, lease: MediaLease) -> None:
    """Close one iterator and lease together in the caller's worker thread.

    Inputs are the optional active iterator plus its pinned lease.  The helper
    returns no value and guarantees the lease close is attempted even if
    generator finalization raises; both operations remain idempotent boundaries.
    """
    try:
        if iterator is not None:
            iterator.close()  # type: ignore[attr-defined]
    finally:
        lease.close()


async def _close_media_off_loop(iterator: Iterator[bytes] | None, lease: MediaLease) -> None:
    """Await cleanup in a worker and finish an in-flight close before cancellation.

    The optional iterator and lease are finalized by one worker call so neither
    store locks nor generator finalizers block asyncio.  A second cancellation
    waits for that already-started bounded cleanup before preserving the caller's
    authoritative ``CancelledError``.
    """
    pending = asyncio.create_task(asyncio.to_thread(_close_media_sync, iterator, lease))
    await _await_executor_future_preserving_cancellation(pending)


async def _next_media_chunk_off_loop(iterator: Iterator[bytes]) -> bytes | None:
    """Await one worker read without closing a generator still executing there.

    Input is the Task-3 iterator and output is one chunk or completion sentinel.
    The read runs in the default worker pool.  If response cancellation arrives,
    this coroutine waits only for that already bounded chunk read to finish
    before re-raising cancellation, allowing the caller's finally block to close
    the generator and lease without a cross-thread ``generator already executing``
    race or active-reader leak.
    """
    loop = asyncio.get_running_loop()
    pending = loop.run_in_executor(None, _next_media_chunk, iterator)
    return await _await_executor_future_preserving_cancellation(pending)


async def _async_media_stream(
    lease: MediaLease,
    byte_range: ByteRange | None,
) -> AsyncIterator[bytes]:
    """Bridge Task-3 synchronous streaming into a cancellation-safe async body.

    Inputs are an already pinned lease and validated byte range; output yields
    bounded byte chunks.  Reads run off the event loop, and normal completion,
    send cancellation, client disconnect, or read failure closes both the
    iterator and lease idempotently before finalization.
    """
    iterator = iter(stream_media(lease, byte_range, method="GET"))
    try:
        while True:
            chunk = await _next_media_chunk_off_loop(iterator)
            if chunk is None:
                return
            yield chunk
    finally:
        # Closing an active generator runs Task-3's finally; the explicit lease
        # close is idempotent defense for cancellation before its first advance.
        await _close_media_off_loop(iterator, lease)


def _consume_head(lease: MediaLease, byte_range: ByteRange | None) -> None:
    """Exhaust the HEAD iterator so its lease-finally executes before response.

    Inputs are one lease and validated range; no value is returned.  The only
    side effect is advancing the zero-body Task-3 generator in a worker thread,
    which validates controls and closes the lease without reading media bytes.
    """
    iterator = iter(stream_media(lease, byte_range, method="HEAD"))
    try:
        for _unused in iterator:
            raise RuntimeError("HEAD media iterator emitted an unexpected body")
    finally:
        iterator.close()
        lease.close()


def create_app(
    *,
    settings: Settings,
    scheduler: Scheduler,
    store: MediaStore,
    health: HealthGate,
    owned_shutdown: Callable[[], Awaitable[None]] | None = None,
) -> FastAPI:
    """Create the authenticated ASGI surface from reviewed injected components.

    Inputs are validated settings plus Scheduler/MediaStore/HealthGate seams;
    output is a configured FastAPI application.  Construction performs no
    external I/O.  Its lifespan starts/stops Scheduler and optionally closes
    only an explicitly runtime-owned dependency afterward; injected components
    otherwise retain caller ownership.
    """
    if not isinstance(settings, Settings):
        raise TypeError("settings must be Settings")
    if not callable(getattr(scheduler, "start", None)) or not callable(getattr(scheduler, "stop", None)):
        raise TypeError("scheduler lifecycle is required")
    if not callable(getattr(store, "open", None)):
        raise TypeError("media store open boundary is required")
    if not callable(getattr(health, "snapshot", None)) or not callable(getattr(health, "can_start", None)):
        raise TypeError("health gate boundary is required")
    if owned_shutdown is not None and not callable(owned_shutdown):
        raise TypeError("owned shutdown must be callable")

    readiness_cache = _HealthReadinessCache(health, _HEALTH_SNAPSHOT_FRESH_SECONDS)

    @asynccontextmanager
    async def lifespan(_app: FastAPI) -> AsyncIterator[None]:
        """Stop Scheduler before closing an explicitly runtime-owned dependency."""
        try:
            await scheduler.start()
            yield
        finally:
            try:
                await scheduler.stop()
            finally:
                if owned_shutdown is not None:
                    await owned_shutdown()

    app = FastAPI(lifespan=lifespan)

    def authenticated_user(request: Request) -> UserContext:
        """Authenticate one browser route through the Task-1 gateway contract."""
        return require_gateway(request, settings)

    @app.exception_handler(RequestValidationError)
    async def validation_error_handler(
        _request: Request,
        _error: RequestValidationError,
    ) -> JSONResponse:
        """Replace reflected Pydantic details with the stable invalid-source code."""
        return _error_response(422, "invalid_source")

    @app.exception_handler(HTTPException)
    async def http_error_handler(_request: Request, error: HTTPException) -> JSONResponse:
        """Map internal/auth HTTP exceptions to non-reflective public codes."""
        if error.status_code in {401, 403}:
            code: PublicErrorCode = "forbidden"
        elif error.status_code == 422:
            code = "invalid_source"
        elif error.status_code == 404:
            code = "not_found"
        else:
            code = "transcode_failed"
        return _error_response(error.status_code, code)

    @app.exception_handler(Exception)
    async def component_error_handler(_request: Request, _error: Exception) -> JSONResponse:
        """Contain unexpected runtime faults behind one stable JSON error.

        The handler deliberately ignores exception text and catches only
        ``Exception``: FastAPI's more-specific HTTP handler remains authoritative
        and asyncio cancellation (a ``BaseException``) preserves its semantics.
        """
        return _error_response(500, "transcode_failed")

    @app.get("/health")
    async def health_route(
        _user: UserContext = Depends(authenticated_user),
    ) -> dict[str, bool]:
        """Return only coarse runtime readiness after gateway authentication.

        The trusted user dependency authorizes the call; output contains one
        boolean and no feature flag, threshold, path, URL, secret, GPU identity,
        or diagnostic.  Side effects are HealthGate's approved read-only probes
        executed off the event loop.
        """
        return {"ready": await readiness_cache.readiness()}

    @app.post("/prepare", response_model=PrepareResponse)
    async def prepare_route(
        source: PrepareRequest,
        user: UserContext = Depends(authenticated_user),
    ) -> PrepareResponse | JSONResponse:
        """Admit or coalesce one authenticated immutable media preparation.

        Inputs are Pydantic-validated source fields and trusted gateway identity;
        output is the strict preparation contract or stable retryable refusal.
        Side effects are delegated to Scheduler only when the feature switch is
        enabled; disabled mode performs no resolver, health, storage, or FFmpeg work.
        """
        if not settings.enabled:
            return _error_response(
                503,
                "health_gate",
                retry_after_ms=_HEALTH_RETRY_AFTER_MS,
                headers={"Retry-After": "1"},
            )
        try:
            job = await scheduler.submit(source, source.purpose, user)
        except QueueFullError as error:
            return _error_response(
                error.status_code,
                "queue_full",
                retry_after_ms=error.retry_after_ms,
                headers={"Retry-After": "1"},
            )
        except HealthGateError as error:
            return _error_response(
                error.status_code,
                "health_gate",
                retry_after_ms=error.retry_after_ms,
                headers={"Retry-After": "1"},
            )
        return _prepare_response(job)

    @app.get("/jobs/{job_id}", response_model=JobStatusResponse)
    async def job_status_route(
        job_id: str,
        user: UserContext = Depends(authenticated_user),
    ) -> JobStatusResponse | JSONResponse:
        """Return public state only to an authenticated owner of the opaque job.

        Inputs are a route identifier and trusted user.  Output is a strict
        status response; missing and cross-owner lookups remain distinct status
        codes but reveal no job/source details.  The operation has no external I/O.
        """
        try:
            job = scheduler.status(job_id, user)
        except KeyError:
            return _error_response(404, "not_found")
        except PermissionError:
            return _error_response(403, "forbidden")
        return _status_response(job)

    @app.delete("/jobs/{job_id}/waiter", response_model=JobStatusResponse)
    async def cancel_waiter_route(
        job_id: str,
        user: UserContext = Depends(authenticated_user),
    ) -> JobStatusResponse | JSONResponse:
        """Remove one authenticated waiter without cancelling shared consumers.

        Inputs are an opaque job id and trusted identity; output is the resulting
        public lifecycle.  Side effects remain Scheduler's in-memory waiter and
        cooperative cancellation policy only, never process/service control here.
        """
        try:
            job = await scheduler.cancel_waiter(job_id, user)
        except KeyError:
            return _error_response(404, "not_found")
        except PermissionError:
            return _error_response(403, "forbidden")
        return _status_response(job)

    async def media_route(
        cache_key: str,
        request: Request,
        _user: UserContext = Depends(authenticated_user),
    ) -> Response:
        """Serve one indexed derived MP4 with exact GET/HEAD/range semantics.

        Inputs are an opaque route key, request method/range, and authenticated
        identity.  Output is 200/206 media, empty HEAD, stable 404, or safe 416.
        Side effects are only MediaStore index touch/open and bounded reads; the
        handler never accepts or returns filesystem paths or Frigate source URLs.
        """
        if _PUBLIC_CACHE_KEY.fullmatch(cache_key) is None:
            return _error_response(404, "not_found")
        try:
            lease = await asyncio.to_thread(store.open, cache_key)
        except Exception:
            return _error_response(404, "not_found")

        # From this point every branch owns the active lease and either consumes
        # Task-3 streaming or closes it explicitly before returning an error.
        try:
            byte_range = parse_range(request.headers.get("Range"), lease.size)
            metadata = response_metadata(byte_range, lease.size)
        except RangeNotSatisfiable as error:
            await _close_media_off_loop(None, lease)
            safe_headers = dict(error.headers)
            safe_headers["Cache-Control"] = "private, max-age=900"
            safe_headers["X-Content-Type-Options"] = "nosniff"
            safe_headers["X-BPP-Error-Code"] = "range_not_satisfiable"
            return Response(status_code=error.status_code, content=b"", headers=safe_headers)
        except Exception:
            await _close_media_off_loop(None, lease)
            return _error_response(404, "not_found")

        safe_headers = dict(metadata.headers)
        safe_headers["Cache-Control"] = "private, max-age=900"
        safe_headers["X-Content-Type-Options"] = "nosniff"
        if request.method == "HEAD":
            try:
                await asyncio.to_thread(_consume_head, lease, byte_range)
            except Exception:
                await _close_media_off_loop(None, lease)
                return _error_response(404, "not_found")
            return Response(status_code=metadata.status_code, content=b"", headers=safe_headers)
        return StreamingResponse(
            _async_media_stream(lease, byte_range),
            status_code=metadata.status_code,
            headers=safe_headers,
        )

    # Register GET and HEAD explicitly so both paths pass through the same auth,
    # index, range, and lease-cleanup implementation.
    app.add_api_route("/media/{cache_key}.mp4", media_route, methods=["GET"])
    app.add_api_route("/media/{cache_key}.mp4", media_route, methods=["HEAD"])
    return app


def create_runtime_app() -> FastAPI:
    """Compose the real least-authority service for Uvicorn's factory mode.

    The function reads validated environment settings, opens one proxy-disabled
    internal HTTP client, validates the two dedicated derived-media roots, and
    wires fixed executable paths into HealthGate/Transcoder/Scheduler.  It does
    not start the app, make network/GPU calls, or control Docker/Frigate; ASGI
    lifespan later starts and stops only Scheduler.
    """
    settings = Settings.from_env()
    # Disable environment proxies and redirects so fixed Frigate authority
    # cannot be rerouted by inherited container variables or upstream responses.
    client = httpx.AsyncClient(trust_env=False, follow_redirects=False)
    resolver = SourceResolver(client, settings)
    cache_root = _CACHE_ROOT.resolve(strict=True)
    work_root = _WORK_ROOT.resolve(strict=True)
    store = MediaStore(
        cache_root,
        work_root,
        cache_limit_bytes=settings.cache_limit_bytes,
        tmpfs_limit_bytes=settings.tmpfs_limit_bytes,
        persistent_free_percent=settings.persistent_free_percent,
        persistent_safety_bytes=settings.persistent_safety_bytes,
        tmpfs_lease_seconds=settings.tmpfs_lease_seconds,
    )
    transcoder = Transcoder(
        _FFMPEG_PATH,
        _FFPROBE_PATH,
        (cache_root, work_root),
        max_output_bytes=settings.tmpfs_limit_bytes,
    )
    health = HealthGate(
        nvidia_smi_path=_NVIDIA_SMI_PATH,
        ffmpeg_path=_FFMPEG_PATH,
        start_temperature_c=settings.gpu_start_temp_c,
        cancel_temperature_c=settings.gpu_cancel_temp_c,
        minimum_free_vram_bytes=settings.minimum_free_vram_bytes,
    )
    scheduler = Scheduler(
        resolver=resolver,
        store=store,
        transcoder=transcoder,
        health=health,
        job_factory=ProbedJobFactory(transcoder),
        waiting_jobs=settings.waiting_jobs,
    )
    return create_app(
        settings=settings,
        scheduler=scheduler,
        store=store,
        health=health,
        owned_shutdown=resolver.aclose,
    )
